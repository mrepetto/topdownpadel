import vm from 'node:vm';import fs from 'node:fs';import assert from 'node:assert/strict';
const c={console,Date,language:'en'};vm.createContext(c);
for(const file of ['kit-bags.js','challenges.js','progression-core.js','store.js'])vm.runInContext(fs.readFileSync('web/'+file,'utf8'),c);
const {Career:C,PadelStore:S}=c,p=C.fresh(),time=Date.UTC(2026,10,5),rows=S.rotation(time);
assert.equal(rows.length,3);assert.equal(new Set(rows.map(x=>x.id)).size,3);
assert.deepEqual(Array.from(rows,x=>x.tier),[1,2,3]);assert.equal(JSON.stringify(S.rotation(time)),JSON.stringify(rows));
assert.notEqual(JSON.stringify(S.rotation(time+5*86400000)),JSON.stringify(rows));
const key=rows[0].key;assert.equal(S.buySkin(p,key,time),false);p.coins=50000;
assert.equal(S.buySkin(p,key,time),true);assert.equal(p.coins,50000-rows[0].price);
const balance=p.coins;assert.equal(S.buySkin(p,key,time),false);assert.equal(p.coins,balance);
assert.equal(S.buySkin(p,rows[1].key,time+5*86400000),false);assert.equal(p.coins,balance);
assert.equal(S.HALLOWEEN_END,Date.parse('2026-11-30T23:00:00Z'));
const before=S.render(p,true,S.HALLOWEEN_END-1),after=S.render(p,true,S.HALLOWEEN_END);
assert(before.includes('HALLOWEEN'));assert(!after.includes('HALLOWEEN'));
assert.equal((before.match(/data-meta="offer"/g)||[]).length,13);
assert.equal((after.match(/data-meta="offer"/g)||[]).length,12);
console.log('PASS store rotation, rarity prices, duplicate/expired/insufficient balance guards, four tiers and Halloween expiry');
const storeArt=[...before.matchAll(/src="(\/store-[^"?]+\.webp)(?:\?[^"]*)?"/g)].map(m=>m[1]);
assert.equal(new Set(storeArt).size,13);
for(const path of storeArt)assert(fs.existsSync('web'+path),'Missing offer artwork '+path);
assert(!before.includes('coin-pile'));assert(!before.includes('/kit-bag-'));
console.log('PASS all 13 exclusive offer illustrations are present; no reused bag or coin-stack collages');
assert.equal(S.offerCountdown(S.HALLOWEEN_END-90061000),'1d 01:01:01');
assert.equal(S.offerCountdown(S.HALLOWEEN_END-1000),'00:00:01');
assert.equal(S.offerCountdown(S.HALLOWEEN_END),null);
assert.equal(S.offerCountdown(S.HALLOWEEN_END+1000),null);
console.log('PASS offer countdown uses fixed expiry, correct day/hour/minute/second rollover and disappears after expiry');
